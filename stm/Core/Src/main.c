static inline uint32_t radian_ccr(float radian)
{
  if (radian < -HALF_PI) radian = -HALF_PI;
  if (radian >  HALF_PI) radian =  HALF_PI;


  float norm = (radian + HALF_PI) / PI;
  return MIN_CCR + (uint32_t)(norm * (MAX_CCR - MIN_CCR) + 0.5f);
}

